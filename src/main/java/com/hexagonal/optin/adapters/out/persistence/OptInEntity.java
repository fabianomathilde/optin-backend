package com.hexagonal.optin.adapters.out.persistence;

import com.hexagonal.optin.domain.Frequency;
import com.hexagonal.optin.domain.OptInStatus;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Id;
import jakarta.persistence.Table;

import java.time.Instant;
import java.time.LocalDate;
import java.util.UUID;

/**
 * JPA entity for the opt_in table (V1 + V3 migrations). Never leaves this package.
 * The id is a UUID assigned by the adapter before saving (ADR 0005), not generated by the database.
 */
@Entity
@Table(name = "opt_in")
class OptInEntity {

    @Id
    @Column(name = "id", nullable = false)
    private UUID id;

    @Column(name = "merchant", length = 14, nullable = false)
    private String merchant;

    @Column(name = "grantee", length = 14, nullable = false)
    private String grantee;

    @Enumerated(EnumType.STRING)
    @Column(name = "frequency", length = 10, nullable = false)
    private Frequency frequency;

    @Column(name = "start_date", nullable = false)
    private LocalDate startDate;

    @Column(name = "valid_until")
    private LocalDate validUntil;

    @Enumerated(EnumType.STRING)
    @Column(name = "status", length = 10, nullable = false)
    private OptInStatus status;

    @Column(name = "revoked_at")
    private Instant revokedAt;

    protected OptInEntity() {
        // required by JPA
    }

    OptInEntity(UUID id, String merchant, String grantee, Frequency frequency,
                LocalDate startDate, LocalDate validUntil, OptInStatus status, Instant revokedAt) {
        this.id = id;
        this.merchant = merchant;
        this.grantee = grantee;
        this.frequency = frequency;
        this.startDate = startDate;
        this.validUntil = validUntil;
        this.status = status;
        this.revokedAt = revokedAt;
    }

    UUID getId() {
        return id;
    }

    String getMerchant() {
        return merchant;
    }

    String getGrantee() {
        return grantee;
    }

    Frequency getFrequency() {
        return frequency;
    }

    LocalDate getStartDate() {
        return startDate;
    }

    LocalDate getValidUntil() {
        return validUntil;
    }

    OptInStatus getStatus() {
        return status;
    }

    Instant getRevokedAt() {
        return revokedAt;
    }
}
